let STYLE_TEMPLATE_BYTES = null;
let LAST_EXPORT_DEBUG = "";

function getStyleExportMode() {
  const el = document.getElementById("styExportMode");
  return el ? el.value : "builtin-psre";
}

function styleVarLen(value) {
  let buffer = value & 0x7f;
  const bytes = [];
  while (value >>= 7) {
    buffer <<= 8;
    buffer |= ((value & 0x7f) | 0x80);
  }
  while (true) {
    bytes.push(buffer & 0xff);
    if (buffer & 0x80) buffer >>= 8;
    else break;
  }
  return bytes;
}

function asciiBytes(s) {
  return [...s].map(c => c.charCodeAt(0));
}

function u32bytes(n) {
  return [(n >>> 24) & 255, (n >>> 16) & 255, (n >>> 8) & 255, n & 255];
}

function chunk(tag, body) {
  return [...asciiBytes(tag), ...u32bytes(body.length), ...body];
}

function padName(name) {
  const b = asciiBytes(name.slice(0, 8));
  while (b.length < 8) b.push(32);
  return b;
}

function metaEvent(tick, type, data) {
  return { tick, bytes: [255, type, ...styleVarLen(data.length), ...data] };
}

function syxEvent(tick, data) {
  return { tick, bytes: [240, ...styleVarLen(data.length), ...data] };
}

function midiEvent(tick, status, data) {
  return { tick, bytes: [status, ...data] };
}

function addVoiceSetup(events, ch, msb, lsb, pc, vol = 100, pan = 64, rev = 40, chorus = 0, tick = 192) {
  events.push(midiEvent(tick, 0xb0 + ch, [0, msb]));
  events.push(midiEvent(tick, 0xb0 + ch, [32, lsb]));
  events.push(midiEvent(tick + 1, 0xc0 + ch, [pc]));
  events.push(midiEvent(tick + 2, 0xb0 + ch, [7, vol]));
  events.push(midiEvent(tick + 2, 0xb0 + ch, [10, pan]));
  events.push(midiEvent(tick + 2, 0xb0 + ch, [91, rev]));
  events.push(midiEvent(tick + 2, 0xb0 + ch, [93, chorus]));
}

function ctab(ch, name, kind) {
  const common = [ch, 1, 15, 255];
  let tail;
  if (kind === "drum") tail = [...common, 7, 255, 255, 255, 255, 0, 2, 1, 0, 6, 0, 127, 1, 0];
  else if (kind === "bass") tail = [...common, 3, 255, 255, 255, 255, 0, 2, 0, 1, 8, 28, 127, 2, 0];
  else if (kind === "introBass") tail = [...common, 3, 255, 248, 0, 255, 0, 0, 0, 0, 8, 28, 127, 1, 0];
  else if (kind === "introChord") tail = [...common, 3, 255, 248, 0, 255, 0, 0, 0, 0, 8, 0, 127, 1, 0];
  else tail = [...common, 3, 255, 255, 255, 255, 0, 2, 1, 2, 7, 0, 127, 1, 0];
  return chunk("Ctab", [ch, ...padName(name), ...tail]);
}

function sdec(text) {
  return chunk("Sdec", asciiBytes(text));
}

function buildPsrECasm() {
  const mainGroup = [
    ...sdec("Main A,Main B,Fill In AA,Fill In BB,Fill In AB,Fill In BA"),
    ...ctab(9, "Drums", "drum"),
    ...ctab(10, "Bass", "bass"),
    ...ctab(11, "Chord1", "chord"),
    ...ctab(12, "Chord2", "chord"),
    ...ctab(13, "Pad", "chord"),
    ...ctab(14, "Phrase", "chord")
  ];

  const introEndingGroup = [
    ...sdec("Intro A,Intro B,Ending A,Ending B"),
    ...ctab(9, "Drums", "drum"),
    ...ctab(10, "Bass", "introBass"),
    ...ctab(11, "Chord1", "introChord"),
    ...ctab(12, "Chord2", "introChord"),
    ...ctab(13, "Pad", "introChord"),
    ...ctab(14, "Phrase", "introChord")
  ];

  const body = [...chunk("CSEG", mainGroup), ...chunk("CSEG", introEndingGroup)];
  return chunk("CASM", body);
}

function buildBuiltInPsrEBase() {
  const ppq = 192;
  const endTick = 14592;
  const events = [];

  events.push(metaEvent(0, 0x58, [4, 2, 24, 8]));
  events.push(metaEvent(0, 0x51, tempoBytes(Number(project.tempo) || 120)));
  events.push(metaEvent(0, 0x02, asciiBytes("Generated by StyleForge Lite")));
  events.push(metaEvent(0, 0x06, asciiBytes("SFF1")));
  events.push(metaEvent(0, 0x03, asciiBytes("StyleForgePSRE")));
  events.push(syxEvent(0, [0x7e, 0x7f, 0x09, 0x01, 0xf7]));
  events.push(metaEvent(0, 0x06, asciiBytes("SInt")));
  events.push(syxEvent(12, [0x43, 0x10, 0x4c, 0x00, 0x00, 0x7e, 0x00, 0xf7]));

  const sections = [
    [768, "Main A"],
    [2304, "Main B"],
    [3840, "Intro A"],
    [5376, "Intro B"],
    [8448, "Fill In AA"],
    [9216, "Fill In AB"],
    [9984, "Fill In BA"],
    [10752, "Fill In BB"],
    [11520, "Ending A"],
    [13056, "Ending B"]
  ];

  for (const [tick, label] of sections) {
    events.push(metaEvent(tick, 0x06, asciiBytes(label)));
    events.push(metaEvent(tick, 0x01, asciiBytes("fn:" + label + "\0")));
  }

  addVoiceSetup(events, 9, 127, 0, 0, 110, 64, 40, 0, 192);      // drums
  addVoiceSetup(events, 10, 0, 0, 33, 105, 48, 35, 0, 204);       // bass
  addVoiceSetup(events, 11, 0, 0, 0, 95, 58, 30, 0, 216);         // chord 1
  addVoiceSetup(events, 12, 0, 0, 24, 90, 70, 30, 0, 228);        // chord 2
  addVoiceSetup(events, 13, 0, 0, 89, 80, 74, 45, 10, 240);       // pad
  addVoiceSetup(events, 14, 0, 0, 0, 95, 64, 30, 0, 252);         // phrase

  events.push({ tick: endTick, bytes: [255, 47, 0] });
  const trk = rebuildTrack(events);
  const header = [...asciiBytes("MThd"), 0, 0, 0, 6, 0, 0, 0, 1, (ppq >> 8) & 255, ppq & 255];
  return new Uint8Array([...header, ...asciiBytes("MTrk"), ...u32bytes(trk.length), ...trk, ...buildPsrECasm()]);
}

function bytesText(a) {
  let s = "";
  for (let i = 0; i < a.length; i++) s += String.fromCharCode(a[i]);
  return s;
}

function readU32(a, i) {
  return ((a[i] << 24) >>> 0) + (a[i + 1] << 16) + (a[i + 2] << 8) + a[i + 3];
}

function readVar(a, i) {
  let v = 0, b = 0;
  do {
    b = a[i++];
    v = (v << 7) + (b & 127);
  } while ((b & 128) && i < a.length);
  return { v, i };
}

function putStatus(msg) {
  const el = document.getElementById("templateStatus");
  if (el) el.textContent = msg;
  else console.log(msg);
}

function chanDataLen(status) {
  const h = status & 240;
  return (h === 192 || h === 208) ? 1 : 2;
}

function findMTrk(a) {
  for (let i = 0; i < a.length - 4; i++) {
    if (a[i] === 77 && a[i + 1] === 84 && a[i + 2] === 114 && a[i + 3] === 107) return i;
  }
  return -1;
}

function parseTrack(a, start, end) {
  let i = start, tick = 0, run = 0;
  const out = [];
  while (i < end) {
    const r = readVar(a, i);
    tick += r.v;
    i = r.i;
    let status = a[i++];
    if (status < 128) {
      i--;
      status = run;
    } else if (status < 240) {
      run = status;
    }

    if (status === 255) {
      const type = a[i++];
      const l = readVar(a, i);
      i = l.i;
      const data = Array.from(a.slice(i, i + l.v));
      i += l.v;
      out.push({ tick, kind: "meta", type, data, bytes: [255, type, ...styleVarLen(data.length), ...data] });
      if (type === 47) break;
    } else if (status === 240 || status === 247) {
      const l = readVar(a, i);
      i = l.i;
      const data = Array.from(a.slice(i, i + l.v));
      i += l.v;
      out.push({ tick, kind: "sys", bytes: [status, ...styleVarLen(data.length), ...data] });
    } else if (status > 0) {
      const n = chanDataLen(status);
      const data = Array.from(a.slice(i, i + n));
      i += n;
      out.push({ tick, kind: "midi", status, bytes: [status, ...data] });
    } else {
      break;
    }
  }
  return out;
}

function findTemplateParts(bytes) {
  const a = Array.from(bytes);
  if (bytesText(a.slice(0, 4)) !== "MThd") throw new Error("Template is not MIDI/STY");
  const ppq = (a[12] << 8) + a[13];
  const m = findMTrk(a);
  if (m < 0) throw new Error("Template has no MTrk");
  const len = readU32(a, m + 4);
  const start = m + 8;
  const end = start + len;
  return { a, ppq, trackStart: start, tail: a.slice(end), events: parseTrack(a, start, end) };
}

function markerInfo(events) {
  const markers = [];
  for (const e of events) {
    if (e.kind === "meta" && e.type === 6) markers.push({ label: bytesText(e.data), tick: e.tick });
  }
  markers.sort((a, b) => a.tick - b.tick);
  const last = events.reduce((m, e) => Math.max(m, e.tick), 0);
  const map = {};
  for (let i = 0; i < markers.length; i++) {
    const next = i < markers.length - 1 ? markers[i + 1].tick : last;
    if (!map[markers[i].label]) {
      map[markers[i].label] = { start: markers[i].tick, end: next, span: Math.max(1, next - markers[i].tick) };
    }
  }
  return map;
}

function tempoMeta() {
  return [255, 81, 3, ...tempoBytes(Number(project.tempo) || 120)];
}

function normalizedKeepEvent(e) {
  if (e.kind === "meta" && e.type === 81) return { tick: e.tick, bytes: tempoMeta() };
  return { tick: e.tick, bytes: e.bytes };
}

function isNoteMidiEvent(e) {
  if (e.kind !== "midi") return false;
  const h = e.status & 240;
  return h === 128 || h === 144;
}

